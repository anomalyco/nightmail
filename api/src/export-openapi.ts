import { mkdir, writeFile } from 'node:fs/promises';
import { createOpenApiApp } from './app.js';
import { createRegisteredDocument, publicDocument } from './openapi-docs.js';
const document = createRegisteredDocument(await createOpenApiApp());
const published = publicDocument(document);
if (process.argv.includes('--sdk')) {
  // Build input only: never copy this full contract into a public directory.
  await mkdir(new URL('../dist/', import.meta.url), { recursive: true });
  await writeFile(new URL('../dist/openapi-sdk.json', import.meta.url), JSON.stringify(document));
}
await writeFile(new URL('../openapi.json', import.meta.url), JSON.stringify(published, null, 2) + '\n');
console.log(`Generated OpenAPI for ${Object.keys(published.paths ?? {}).length} paths.`);

// Every property name the description defines, walked as JSON Schema (properties, items, combinators), never into an
// example, default, enum or const value: the only keys a logged schema path keeps (schemaIssues in log.ts).
type Schema = { [key: string]: unknown };
const names = new Set<string>();
const isObject = (value: unknown): value is Schema => !!value && typeof value === 'object' && !Array.isArray(value);
function walk(schema: unknown) {
  if (!isObject(schema)) return;
  if (isObject(schema.properties)) for (const [name, property] of Object.entries(schema.properties)) { names.add(name); walk(property); }
  for (const key of ['items', 'additionalProperties', 'not', 'if', 'then', 'else', 'contains', 'propertyNames', 'unevaluatedItems', 'unevaluatedProperties']) walk(schema[key]);
  for (const key of ['allOf', 'anyOf', 'oneOf', 'prefixItems']) if (Array.isArray(schema[key])) for (const item of schema[key]) walk(item);
  for (const key of ['patternProperties', '$defs', 'dependentSchemas']) if (isObject(schema[key])) for (const item of Object.values(schema[key])) walk(item);
}
const content = (value: unknown) => { if (isObject(value)) for (const media of Object.values(value)) if (isObject(media)) walk(media.schema); };
for (const schema of Object.values<unknown>(document.components?.schemas ?? {})) walk(schema);
for (const item of Object.values<unknown>(document.paths ?? {})) for (const operation of Object.values(isObject(item) ? item : {})) {
  if (!isObject(operation)) continue;
  for (const parameter of Array.isArray(operation.parameters) ? operation.parameters : []) if (isObject(parameter)) walk(parameter.schema);
  if (isObject(operation.requestBody)) content(operation.requestBody.content);
  for (const answer of Object.values(isObject(operation.responses) ? operation.responses : {})) if (isObject(answer)) content(answer.content);
}
const sorted = [...names].sort((a, b) => a < b ? -1 : a > b ? 1 : 0);
await writeFile(new URL('./api-field-names.ts', import.meta.url), `// Generated by src/export-openapi.ts (bun run openapi) from openapi.json; do not edit. Every property name the API's
// OpenAPI description defines: a logged schema path keeps a key only when it is one of these (schemaIssues in log.ts).
export const API_FIELD_NAMES: readonly string[] = [
${sorted.map(name => `  ${JSON.stringify(name)},`).join('\n')}
];
`);
console.log(`Generated ${sorted.length} API field names.`);
